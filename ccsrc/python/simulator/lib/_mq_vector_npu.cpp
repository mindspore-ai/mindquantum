[[noreturn]] void ThrowAclError(const char* operation, aclError status) {
    std::ostringstream message;
    message << "mqvector_npu: " << operation << " failed with ACL error " << status;
    const auto* detail = aclGetRecentErrMsg();
    if (detail != nullptr && detail[0] != '\0') {
        message << ": " << detail;
    }
    throw std::runtime_error(message.str());
}

void CheckAcl(aclError status, const char* operation) {
    if (status != ACL_SUCCESS) {
        ThrowAclError(operation, status);
    }
}

class AscendRuntime {
 public:
    static void EnsureReady() {
        static std::once_flag init_once;
        std::call_once(init_once, [] {
            const auto status = aclInit(nullptr);
            if (status != ACL_SUCCESS && status != ACL_ERROR_REPEAT_INITIALIZE) {
                ThrowAclError("aclInit", status);
            }
        });
        CheckAcl(aclrtSetDevice(kDeviceId), "aclrtSetDevice");
    }
};

