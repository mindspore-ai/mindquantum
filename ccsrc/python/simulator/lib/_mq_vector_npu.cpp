    void AppendSwapGate(std::vector<CircuitGate>& operations, mindquantum::qbit_t first,
                        mindquantum::qbit_t second) const {
        if (first == second) {
            return;
        }
        const auto target_mask = (uint64_t{1} << static_cast<uint32_t>(first))
                                 | (uint64_t{1} << static_cast<uint32_t>(second));
        operations.push_back(
            {target_mask, 0U, kTwoQubitGate, static_cast<uint32_t>(TwoQubitOperation::kSwap), {}, 1.0F, 0.0F});
    }

    void AppendQubitMapRestore(std::vector<CircuitGate>& operations,
                               std::vector<mindquantum::qbit_t>& logical_to_physical) const {
        std::vector<mindquantum::qbit_t> physical_to_logical(logical_to_physical.size());
        for (mindquantum::qbit_t logical = 0; logical < n_qubits_; ++logical) {
            physical_to_logical[static_cast<std::size_t>(logical_to_physical[logical])] = logical;
        }
        for (mindquantum::qbit_t logical = 0; logical < n_qubits_; ++logical) {
            const auto desired_physical = logical;
            const auto current_physical = logical_to_physical[static_cast<std::size_t>(logical)];
            if (current_physical == desired_physical) {
                continue;
            }
            const auto displaced_logical = physical_to_logical[static_cast<std::size_t>(desired_physical)];
            AppendSwapGate(operations, desired_physical, current_physical);
            logical_to_physical[static_cast<std::size_t>(logical)] = desired_physical;
            logical_to_physical[static_cast<std::size_t>(displaced_logical)] = current_physical;
            physical_to_logical[static_cast<std::size_t>(desired_physical)] = logical;
            physical_to_logical[static_cast<std::size_t>(current_physical)] = displaced_logical;
        }
    }

