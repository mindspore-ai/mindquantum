    void LaunchCircuit(const std::vector<CircuitGate>& operations) {
        AscendRuntime::EnsureReady();
        if (operations.empty()) {
            return;
        }
        if (operations.size() > std::numeric_limits<uint32_t>::max()) {
            throw std::invalid_argument("mqvector_npu circuit contains too many gates.");
        }

        const auto gate_bytes = operations.size() * sizeof(CircuitGate);
        try {
            if (!CircuitCacheMatches(operations)) {
                EnsureDeviceGateCapacity(gate_bytes);
                cached_operations_.clear();
                CheckAcl(aclrtMemcpy(device_gates_, gate_bytes, operations.data(), gate_bytes,
                                     ACL_MEMCPY_HOST_TO_DEVICE),
                         "aclrtMemcpy(circuit gates)");
                cached_operations_ = operations;
            }
            constexpr uint32_t block_dim = 1;
            CheckAcl(static_cast<aclError>(aclrtlaunch_mqvector_apply_circuit(
                         block_dim, stream_, device_state_, device_gates_, static_cast<uint64_t>(dim_),
                         static_cast<uint32_t>(operations.size()))),
                     "aclrtlaunch_mqvector_apply_circuit");
            SynchronizeStream();
        } catch (...) {
            (void) aclrtSynchronizeStream(stream_);
            throw;
        }
    }

    bool CircuitCacheMatches(const std::vector<CircuitGate>& operations) const {
        if (cached_operations_.size() != operations.size()) {
            return false;
        }
        return std::equal(
            cached_operations_.begin(), cached_operations_.end(), operations.begin(),
            [](const CircuitGate& cached, const CircuitGate& current) {
                return cached.target_mask == current.target_mask && cached.control_mask == current.control_mask
                       && cached.kind == current.kind && cached.operation == current.operation
                       && cached.matrix.m00_real == current.matrix.m00_real
                       && cached.matrix.m00_imag == current.matrix.m00_imag
                       && cached.matrix.m01_real == current.matrix.m01_real
                       && cached.matrix.m01_imag == current.matrix.m01_imag
                       && cached.matrix.m10_real == current.matrix.m10_real
                       && cached.matrix.m10_imag == current.matrix.m10_imag
                       && cached.matrix.m11_real == current.matrix.m11_real
                       && cached.matrix.m11_imag == current.matrix.m11_imag
                       && cached.cosine == current.cosine && cached.sine == current.sine;
            });
    }

    void EnsureDeviceGateCapacity(std::size_t required_bytes) {
        if (device_gates_ != nullptr && device_gates_capacity_ >= required_bytes) {
            return;
        }

        SynchronizeStream();
        void* replacement = nullptr;
        CheckAcl(aclrtMalloc(&replacement, required_bytes, ACL_MEM_MALLOC_HUGE_FIRST),
                 "aclrtMalloc(circuit gates)");
        if (device_gates_ != nullptr) {
            (void) aclrtFree(device_gates_);
        }
        device_gates_ = replacement;
        device_gates_capacity_ = required_bytes;
        cached_operations_.clear();
    }

    void LaunchCircuitLegacy(const std::vector<CircuitGate>& operations) {
        for (const auto& operation : operations) {
            if (operation.kind == kTwoQubitGate) {
                LaunchTwoQubit(static_cast<TwoQubitOperation>(operation.operation), operation.cosine, operation.sine,
                               operation.target_mask, operation.control_mask, false);
            } else {
                LaunchMatrix(operation.matrix, operation.target_mask, operation.control_mask, false);
            }
        }
        SynchronizeStream();
    }

    struct LocalSegment {
        std::size_t begin;
        std::size_t count;
        uint64_t local_mask;
        bool is_local;
    };

