uint32_t PopCount(uint64_t value) {
    uint32_t count = 0;
    while (value != 0) {
        value &= value - 1U;
        ++count;
    }
    return count;
}

uint64_t ScatterBitsHost(uint64_t value, uint64_t mask) {
    uint64_t result = 0U;
    uint64_t source_bit = 1U;
    while (mask != 0U) {
        const uint64_t target_bit = mask & (~mask + 1U);
        if ((value & source_bit) != 0U) {
            result |= target_bit;
        }
        source_bit <<= 1U;
        mask ^= target_bit;
    }
    return result;
}

uint32_t PackLocalMaskHost(uint64_t mask, uint64_t local_mask) {
    uint32_t result = 0U;
    uint32_t local_bit = 1U;
    while (local_mask != 0U) {
        const uint64_t physical_bit = local_mask & (~local_mask + 1U);
        if ((mask & physical_bit) != 0U) {
            result |= local_bit;
        }
        local_bit <<= 1U;
        local_mask ^= physical_bit;
    }
    return result;
}

float EncodeLocalMeta(uint32_t value) {
    constexpr uint32_t kLocalMetaFloatBase = 0x3F800000U;
    union {
        uint32_t bits;
        float value;
    } encoded;
    encoded.bits = kLocalMetaFloatBase | value;
    return encoded.value;
}

