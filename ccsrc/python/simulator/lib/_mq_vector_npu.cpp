uint32_t LocalTileCacheQubits() {
    const auto* value = std::getenv("MQVECTOR_NPU_LOCAL_CACHE_QUBITS");
    if (value == nullptr || value[0] == '\0') {
        return kDefaultCachedLocalQubits;
    }

    errno = 0;
    char* end = nullptr;
    const auto parsed = std::strtoul(value, &end, 10);
    if (errno != 0 || end == value || *end != '\0' || parsed == 0 || parsed > kMaxCachedLocalQubits) {
        throw std::invalid_argument(
            "MQVECTOR_NPU_LOCAL_CACHE_QUBITS must be an integer between 1 and "
            + std::to_string(kMaxCachedLocalQubits) + ".");
    }
    return static_cast<uint32_t>(parsed);
}

uint32_t LegacyBlockDim(mindquantum::qbit_t n_qubits) {
    const auto* value = std::getenv("MQVECTOR_NPU_LEGACY_BLOCK_DIM");
    if (value == nullptr || value[0] == '\0') {
        if (n_qubits >= 26) {
            return 4096;
        }
        return kDefaultLegacyBlockDim;
    }

    errno = 0;
    char* end = nullptr;
    const auto parsed = std::strtoul(value, &end, 10);
    if (errno != 0 || end == value || *end != '\0' || parsed == 0 || parsed > kMaxLegacyBlockDim) {
        throw std::invalid_argument(
            "MQVECTOR_NPU_LEGACY_BLOCK_DIM must be an integer between 1 and "
            + std::to_string(kMaxLegacyBlockDim) + ".");
    }
    return static_cast<uint32_t>(parsed);
}

py::array_t<uint32_t> ProbeBlockDim(uint32_t block_dim) {
    if (block_dim == 0 || block_dim > kMaxLegacyBlockDim) {
        throw std::invalid_argument(
            "mqvector_npu block-dimension probe accepts values between 1 and "
            + std::to_string(kMaxLegacyBlockDim) + ".");
    }

    AscendRuntime::EnsureReady();
    // Keep each block record on its own 64B cache line. Otherwise concurrent
    // scalar writes from AIV blocks can overwrite neighboring records.
    constexpr std::size_t kRecordWidth = 16;
    std::vector<uint32_t> result(block_dim * kRecordWidth, std::numeric_limits<uint32_t>::max());
    const auto bytes = result.size() * sizeof(uint32_t);
    aclrtStream stream = nullptr;
    void* device_result = nullptr;
    try {
        CheckAcl(aclrtCreateStream(&stream), "aclrtCreateStream(block-dimension probe)");
        CheckAcl(aclrtMalloc(&device_result, bytes, ACL_MEM_MALLOC_HUGE_FIRST), "aclrtMalloc(block-dimension probe)");
        CheckAcl(aclrtMemcpy(device_result, bytes, result.data(), bytes, ACL_MEMCPY_HOST_TO_DEVICE),
                 "aclrtMemcpy(block-dimension probe host-to-device)");
        CheckAcl(static_cast<aclError>(
                     aclrtlaunch_mqvector_probe_block_dim(block_dim, stream, device_result, block_dim)),
                 "aclrtlaunch_mqvector_probe_block_dim");
        CheckAcl(aclrtSynchronizeStream(stream), "aclrtSynchronizeStream(block-dimension probe)");
        CheckAcl(aclrtMemcpy(result.data(), bytes, device_result, bytes, ACL_MEMCPY_DEVICE_TO_HOST),
                 "aclrtMemcpy(block-dimension probe device-to-host)");
        CheckAcl(aclrtFree(device_result), "aclrtFree(block-dimension probe)");
        device_result = nullptr;
        CheckAcl(aclrtDestroyStream(stream), "aclrtDestroyStream(block-dimension probe)");
        stream = nullptr;
    } catch (...) {
        if (stream != nullptr) {
            (void) aclrtSynchronizeStream(stream);
        }
        if (device_result != nullptr) {
            (void) aclrtFree(device_result);
        }
        if (stream != nullptr) {
            (void) aclrtDestroyStream(stream);
        }
        throw;
    }

    py::array_t<uint32_t> output(result.size());
    std::copy(result.begin(), result.end(), output.mutable_data());
    return output;
}

Matrix2x2 MakeMatrix(mindquantum::GateID id, float angle) {
    constexpr float kInvSqrt2 = 0.7071067811865475244F;
    switch (id) {
        case mindquantum::GateID::X:
        case mindquantum::GateID::CNOT:
            return {0.0F, 0.0F, 1.0F, 0.0F, 1.0F, 0.0F, 0.0F, 0.0F};
        case mindquantum::GateID::Y:
            return {0.0F, 0.0F, 0.0F, -1.0F, 0.0F, 1.0F, 0.0F, 0.0F};
        case mindquantum::GateID::Z:
        case mindquantum::GateID::CZ:
            return {1.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F, -1.0F, 0.0F};
        case mindquantum::GateID::H:
            return {kInvSqrt2, 0.0F, kInvSqrt2, 0.0F, kInvSqrt2, 0.0F, -kInvSqrt2, 0.0F};
        case mindquantum::GateID::RX: {
            const auto cosine = std::cos(angle * 0.5F);
            const auto sine = std::sin(angle * 0.5F);
            return {cosine, 0.0F, 0.0F, -sine, 0.0F, -sine, cosine, 0.0F};
        }
        case mindquantum::GateID::RY: {
            const auto cosine = std::cos(angle * 0.5F);
            const auto sine = std::sin(angle * 0.5F);
            return {cosine, 0.0F, -sine, 0.0F, sine, 0.0F, cosine, 0.0F};
        }
        case mindquantum::GateID::RZ: {
            const auto cosine = std::cos(angle * 0.5F);
            const auto sine = std::sin(angle * 0.5F);
            return {cosine, -sine, 0.0F, 0.0F, 0.0F, 0.0F, cosine, sine};
        }
        case mindquantum::GateID::PS:
            return {1.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F, std::cos(angle), std::sin(angle)};
        default:
            throw std::runtime_error(kUnsupportedMsg);
    }
}

TwoQubitOperation MakeTwoQubitOperation(mindquantum::GateID id) {
    switch (id) {
        case mindquantum::GateID::SWAP:
            return TwoQubitOperation::kSwap;
        case mindquantum::GateID::Rxx:
            return TwoQubitOperation::kRxx;
        case mindquantum::GateID::Ryy:
            return TwoQubitOperation::kRyy;
        case mindquantum::GateID::Rzz:
            return TwoQubitOperation::kRzz;
        default:
            throw std::runtime_error(kUnsupportedMsg);
    }
}

